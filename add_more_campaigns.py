def append_campaigns():
    if os.path.exists(DATA_FILE):
        with open(DATA_FILE, 'r', encoding='utf-8') as f:
            data = json.load(f)
    else:
        print("Data file missing!")
        return

    if 'campaigns' not in data:
        data['campaigns'] = []

    # Get existing names to avoid duplicates
    existing_names = [c.get('name') for c in data['campaigns']]
    
    count = 0
    for c in EXTRA_CAMPAIGNS:
        if c['name'] not in existing_names:
            c['id'] = int(time.time()) + count + 100 # Add offset
            c['image_urls'] = [] 
            data['campaigns'].append(c)
            count += 1
            print(f"Added: {c['name']}")
    
    with open(DATA_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=4, ensure_ascii=False)
    print(f"✅ Added {count} new campaigns.")

if __name__ == "__main__":
    append_campaigns()
