import { t } from '../i18n';

/** "Question of the day" for days when there's nothing obvious to write. One per day, the same all day. */
export const PROMPTS = [
  'מה הדבר הכי מצחיק שקרה לך השבוע?',
  'למי היית רוצה להגיד תודה היום, ועל מה?',
  'מה עשית היום שאתה גאה בו, אפילו קצת?',
  'איזה שיר מתאר את היום שלך?',
  'מה היה הרגע הכי שקט ביום?',
  'מה למדת היום — בבית ספר, בעבודה או על עצמך?',
  'מי גרם לך לחייך היום?',
  'אם היום היה צבע, איזה צבע הוא היה? למה?',
  'מה מטריד אותך בזמן האחרון?',
  'מה אתה מחכה לו השבוע?',
  'מה היית אומר לעצמך מלפני שנה?',
  'איזה דבר קטן עשה לך טוב היום?',
  'על מה דיברת הכי הרבה היום?',
  'מה היית רוצה לעשות אחרת מחר?',
  'איזה חלום יש לך לשנה הקרובה?',
  'מה הדבר האחרון שגרם לך לצחוק בקול?',
  'מי האדם שהכי קל לך לדבר איתו? למה?',
  'מה עשית היום בשביל הגוף שלך?',
  'אם היית יכול לחזור לרגע אחד היום, איזה?',
  'מה מישהו אמר לך היום שנשאר לך בראש?',
  'מה הדבר שהכי חסר לך עכשיו?',
  'איזו החלטה קיבלת היום?',
  'מה מרגיע אותך כשקשה?',
  'מה היית רוצה שאנשים יידעו עליך?',
  'מה הדבר הכי טעים שאכלת השבוע?',
  'איפה היית רוצה להיות עכשיו?',
  'מה עשה לך כעס או תסכול היום, ואיך התמודדת?',
  'איזה הישג קטן השגת השבוע?',
  'מה התחביב שהכי כיף לך בו כרגע?',
  'למי התגעגעת היום?',
];

export function promptOfTheDay(d = new Date()): string {
  const day = Math.floor((d.getTime() - new Date(d.getFullYear(), 0, 0).getTime()) / 86400000);
  return t(PROMPTS[day % PROMPTS.length]);
}
